-- ParkFlow reusable-card migration.
-- Run against the existing ParkFlow database. This migration does not delete
-- existing users, rates, tickets, or reports.

CREATE TABLE IF NOT EXISTS cards (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    card_code VARCHAR(32) NOT NULL,
    status ENUM('available', 'in_use', 'lost', 'disabled') NOT NULL DEFAULT 'available',
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    UNIQUE KEY uq_cards_code (card_code),
    KEY idx_cards_status (status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

ALTER TABLE vehicles_tickets
    ADD COLUMN card_id BIGINT UNSIGNED NULL AFTER id,
    ADD KEY idx_tickets_card (card_id),
    ADD COLUMN active_card_id BIGINT UNSIGNED
        GENERATED ALWAYS AS (IF(status = 'active' AND card_id IS NOT NULL, card_id, NULL)) STORED,
    ADD UNIQUE KEY uq_tickets_one_active_card (active_card_id);

ALTER TABLE vehicles_tickets
    ADD CONSTRAINT fk_tickets_card
        FOREIGN KEY (card_id) REFERENCES cards (id);

